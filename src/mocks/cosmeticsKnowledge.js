/**
 * @param {string} userText
 * @param {string} offTopicReply
 * @returns {string}
 */
export function pickDetailedCosmeticsReply(userText, offTopicReply) {
  const text = normalize(userText);
  if (!text) return offTopicReply;

  const care = hits(text, CARE_PATTERNS) > 0;
  const unrelated = isUnrelated(text);

  if (unrelated && !care) return offTopicReply;

  if (/привет|здравств|добр(ый|ое|ого|ая)|доброго/.test(text) && text.length < 40 && !care) {
    return GREETING;
  }

  if (/кто ты|что (ты )?умеешь|чем помо(жешь|жете)|что можешь/.test(text)) {
    return GREETING;
  }

  let best = null;
  let bestPriority = -1;
  let bestScore = 0;

  for (const topic of TOPICS) {
    if (topic.skip?.some((pattern) => pattern.test(text))) continue;
    if (topic.requires && !topic.requires.every((pattern) => pattern.test(text))) {
      continue;
    }
    const score = hits(text, topic.patterns) * (topic.weight || 1);
    if (!score) continue;
    const priority = topic.priority ?? 1;
    if (priority > bestPriority || (priority === bestPriority && score > bestScore)) {
      best = topic;
      bestPriority = priority;
      bestScore = score;
    }
  }

  if (best) {
    if (unrelated) {
      return `${best.answer}\n\nПо заказу, оплате и доставке точные условия подскажет продавец — для этого и нужен телефон в шапке. По самому уходу могу разбирать дальше здесь.`;
    }
    return best.answer;
  }

  if (/спасибо|благодар/.test(text) && !care) {
    return 'Пожалуйста. Если захотите, можем так же подробно разобрать тип кожи, порядок утро/вечер, SPF, ретинол или состав конкретного средства.';
  }

  return DEFAULT_CARE;
}
