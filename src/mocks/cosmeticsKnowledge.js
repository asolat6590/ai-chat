function normalize(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .trim();
}

function hits(text, patterns) {
  return patterns.reduce((count, pattern) => count + (pattern.test(text) ? 1 : 0), 0);
}

export function isCareQuestion(text) {
  return hits(normalize(text), CARE_PATTERNS) > 0;
}

function isUnrelated(text) {
  return hits(text, UNRELATED_PATTERNS) > 0;
}

