/**
 * Простой подбор ответа ассистента по тексту пользователя (мок).
 * @param {string} userText
 * @returns {string}
 */
export function pickMockResponse(userText) {
  const t = userText.toLowerCase().trim();

  if (/привет|здравств|добр(ый|ое|ого)/.test(t)) {
    return 'Привет! Чем могу помочь сегодня?';
  }
  if (/тариф|цен|стоим|оплат|подписк/.test(t)) {
    return 'У нас есть базовый (бесплатный), Pro и Business. На странице «Тарифы» можно сравнить лимиты. Нужна помощь с выбором?';
  }
  if (/начать|старт|регистр|подключ/.test(t)) {
    return 'Чтобы начать: зарегистрируйтесь, подтвердите email и откройте панель управления. Первый проект создаётся за пару минут.';
  }
  if (/поддерж|проблем|ошибк|не работ/.test(t)) {
    return 'Опишите, что именно не получается — шаги и текст ошибки. Я подскажу типовые решения или передам запрос в поддержку.';
  }
  if (/менеджер|человек|оператор|связ/.test(t)) {
    return 'Могу оформить заявку на звонок менеджера. Оставьте удобное время и email — мы свяжемся в течение рабочего дня.';
  }
  if (/спасибо|благодар/.test(t)) {
    return 'Всегда рад помочь! Если появятся ещё вопросы — пишите.';
  }

  return 'Спасибо за сообщение. Я уточню детали: расскажите подробнее, что вас интересует — тарифы, настройка или техническая проблема?';
}
