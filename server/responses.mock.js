import { isCosmeticsRelated } from './cosmeticsTopics.js';
import { getSellerRedirectMessage } from './shop.config.js';

/**
 * @param {string} userText
 * @returns {string}
 */
export function pickMockResponse(userText) {
  if (!isCosmeticsRelated(userText)) {
    return getSellerRedirectMessage();
  }

  const t = userText.toLowerCase().trim();

  if (/привет|здравств|добр(ый|ое|ого)/.test(t)) {
    return 'Здравствуйте! Подскажу по уходу и косметике: тип кожи, состав, как сочетать средства. Что вас интересует?';
  }
  if (/сух|увлажн/.test(t)) {
    return 'Для сухой кожи обычно подходят мягкое очищение, увлажняющая сыворотка с гиалуроновой кислотой и плотный крем с ceramides. Уточните, есть ли чувствительность или шелушение?';
  }
  if (/жирн|акне|прыщ/.test(t)) {
    return 'При жирной и проблемной коже часто выбирают лёгкий гель для умывания, некomedogenic увлажнение и точечные средства с BHA/ниacinamide. Расскажите, какие средства уже используете?';
  }
  if (/spf|солнц|загар/.test(t)) {
    return 'SPF лучше наносить каждый день, обновляя каждые 2–3 часа на солнце. Для города часто достаточно SPF 30–50. Нужен вариант под макияж или для пляжа?';
  }
  if (/состав|ингредиент|ретинол|кислот/.test(t)) {
    return 'При выборе по составу смотрите на тип кожи и сочетание активов: например, ретинол — вечером, SPF — утром. Напишите название средства или цель ухода — подскажу точнее.';
  }
  if (/волос|шампун|бальзам/.test(t)) {
    return 'Для волос важны тип (сухие/жирные/окрашенные) и частота мытья. Обычно: шампунь по типу кожи головы + кондиционер/маска на длину. Что беспокоит — сухость, ломкость или выпадение?';
  }
  if (/макияж|тональн|помад|туш/.test(t)) {
    return 'По декоративной косметике подскажу по текстуре и типу кожи: например, для жирной кожи часто берут матирующий тон, для сухой — увлажняющий. Какой продукт подбираете?';
  }

  return 'Расскажите подробнее: тип кожи или волос, цель ухода и какие средства уже есть — помогу с подбором косметики.';
}
